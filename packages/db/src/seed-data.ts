// Realistic seed content for a fullstack .NET + React developer who's also
// learning English and computer-science fundamentals. Consumed by src/seed.ts.
//
// GOAL (reseed 2026-06): cards that look like REAL daily usage — full-bodied
// explanations with code blocks, mermaid diagrams, LaTeX formulas, comparison
// tables and markdown structure — not terse one-line stubs. The seed doubles as
// a live showcase of every rich-content feature the renderer supports.
//
// Each seed entry is a NOTE (note-types M1 model). A note references a builtin
// note-type by `kind`, carries `fields` (field-name → value), and may carry
// note-level `tags`. The seeder runs `generateCards` over the note-type + field
// values to produce one-or-more `cards` rows, then replays each note's
// `ratings` through ts-fsrs onto the generated card(s).
//
// ── Authoring contract (must match apps/web/src/lib/render-card.tsx) ──────────
// Field values are MARKDOWN SOURCE. markdown → HTML → sanitize happens at the
// render edge, never here. So:
//   * Code blocks:  ```ts ``` / ```sql ``` / ```bash ``` / ```json ``` / ```csharp ```.
//                   Highlighted langs: ts js python bash json sql xml css go rust
//                   markdown yaml. `csharp` is NOT in that set → it renders as a
//                   plain monospace block (no colours) — still a proper code block.
//   * Math (KaTeX): INLINE `\( … \)`, DISPLAY `\[ … \]`. In a TS string a single
//                   backslash must be DOUBLED: `'\\( O(\\log n) \\)'` produces the
//                   source `\( O(\log n) \)`. Put display math on its own line with
//                   blank lines around it so it renders as a centred block.
//   * Mermaid:      a ```mermaid ``` fence (rendered to an SVG island, theme dark,
//                   securityLevel strict). Quote node labels that contain special
//                   chars: `A["O(log n)"]`.
//   * Tables / headings / lists / blockquotes: standard markdown. ALWAYS leave a
//                   blank line before a fence / table / list / heading / quote so
//                   markdown-it parses it as its own block.
//   * `<T>` and other angle-bracket tokens go inside inline-code backticks
//     (`` `<T>` ``) so they (a) display literally and (b) survive the engine's
//     plaintext extraction (a bare `<T>` is stripped → empty front → card skipped).
//   * NEVER emit a literal `{{Front}}` / `{{Back}}` / `{{Text}}` / `{{Extra}}`
//     token inside a field value (the cloze `{{c1::…}}` markup is the only
//     double-brace form the engine expects). JSX single-brace `{x}` is fine.

import { type Rating, type RenderKind } from '@reomi/shared';

export type DeckColor = 'lime' | 'amber' | 'violet' | 'sky' | 'rose' | 'neutral';

export interface NoteSeed {
  /** Which builtin note-type backs this note. Defaults to 'basic'. */
  kind?: Extract<RenderKind, 'basic' | 'cloze' | 'typein'>;
  /** Field values keyed by field name. MARKDOWN SOURCE (rendered at the edge). */
  fields: Record<string, string>;
  tags?: string[];
  /** Replay these ratings to shape FSRS state. Omit → new card. */
  ratings?: Rating[];
}

export interface DeckSeed {
  name: string;
  color: DeckColor;
  children?: DeckSeed[];
  notes?: NoteSeed[];
}

/**
 * Join markdown lines with single newlines. Writing each line as a plain quoted
 * string keeps code-fence/mermaid backticks and `$` literal (no collision with a
 * TS template literal) and keeps math escaping readable (`'\\( … \\)'`). Use an
 * empty-string element `''` to emit the blank line markdown needs before a fence,
 * table, list, heading or blockquote.
 */
const md = (...lines: string[]): string => lines.join('\n');

interface NoteOpts {
  tags?: string[];
  ratings?: Rating[];
}

/** Basic front/back note (markdown source on both sides). */
function basic(front: string, back: string, opts: NoteOpts = {}): NoteSeed {
  return { kind: 'basic', fields: { Front: front, Back: back }, tags: opts.tags, ratings: opts.ratings };
}

/** Cloze note — `{{c1::answer}}` markup in `text`, optional `extra` reveal note. */
function cloze(text: string, extra: string, opts: NoteOpts = {}): NoteSeed {
  return { kind: 'cloze', fields: { Text: text, Extra: extra }, tags: opts.tags, ratings: opts.ratings };
}

/** Type-in note — the answer is typed and LCS-diffed against `back`. */
function typein(front: string, back: string, opts: NoteOpts = {}): NoteSeed {
  return { kind: 'typein', fields: { Front: front, Back: back }, tags: opts.tags, ratings: opts.ratings };
}

